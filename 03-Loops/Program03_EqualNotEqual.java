class Program03_EqualNotEqual {

    public static void main(String[] args) {

        int number1 = 10;
        int number2 = 20;

        if (number1 == number2) {
            System.out.println("Numbers are equal");
        } else {
            System.out.println("Numbers are not equal");
        }

        if (number1 != number2) {
            System.out.println("Numbers are not equal");
        } else {
            System.out.println("Numbers are equal");
        }
    }
}