class Program01_StringCreation {

    public static void main(String[] args) {

        // 1. Using a string literal
        String firstString = "Hello Java";

        // 2. Using String constructor
        String secondString = new String("Hello Java");

        System.out.println("String using literal: " + firstString);
        System.out.println("String using constructor: " + secondString);
    }
}